#!/usr/bin/env python3
"""Generate a matching file-ID table, decoder mapping, and CMake source list.

IDs are indices in the sorted path list, so use the generated log_file_ids.json
with the firmware build that produced it. CMake writes these files into its
build directory. Without --output-dir, the original checked-in table location
and --check workflow remain available.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

# Directories containing code that can run on the OBC and produce logs
SCAN_DIRS = ["obc", "interfaces"]

SOURCE_SUFFIXES = {".c", ".h"}

LOG_MACROS = {
    "LOG_TRACE",
    "LOG_DEBUG",
    "LOG_INFO",
    "LOG_WARN",
    "LOG_ERROR",
    "LOG_FATAL",
    "LOG_TRACE_FROM_ISR",
    "LOG_DEBUG_FROM_ISR",
    "LOG_INFO_FROM_ISR",
    "LOG_WARN_FROM_ISR",
    "LOG_ERROR_FROM_ISR",
    "LOG_FATAL_FROM_ISR",
    "LOG_ERROR_CODE",
    "LOG_ERROR_CODE_FROM_ISR",
    "LOG_IF_ERROR_CODE",
    "RETURN_IF_ERROR_CODE",
    "RETURN_AND_GIVE_IF_ERROR_CODE",
    "configASSERT",
    "ASSERT",
}
IDENTIFIER_RE = re.compile(r"\b[A-Za-z_]\w*\b")
DEFINE_RE = re.compile(
    r"^[ \t]*#[ \t]*define[ \t]+([A-Za-z_]\w*)(?:\([^)]*\))?[ \t]*(.*)$",
    re.MULTILINE,
)
COMMENT_OR_LITERAL_RE = re.compile(
    r'/\*.*?\*/|//[^\n]*|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'',
    re.DOTALL,
)

OUT_DIR = REPO_ROOT / "obc" / "shared" / "logging"
HEADER_PATH = OUT_DIR / "obc_log_file_ids.h"
SOURCE_PATH = OUT_DIR / "obc_log_file_ids.c"
JSON_PATH = OUT_DIR / "log_file_ids.json"

GENERATED_NOTICE = "Generated by scripts/gen_log_file_ids.py. DO NOT EDIT MANUALLY."


def find_logging_files(repo_root: Path = REPO_ROOT) -> list[str]:
    """Find direct logging/assert calls and calls to macros that wrap them."""
    contents: dict[str, str] = {}
    for scan_dir in SCAN_DIRS:
        for path in (repo_root / scan_dir).rglob("*"):
            if path.suffix not in SOURCE_SUFFIXES or not path.is_file():
                continue
            # Join multiline macros, then ignore examples in comments/strings.
            content = re.sub(r"\\\r?\n", "", path.read_text(errors="ignore"))
            contents[path.relative_to(repo_root).as_posix()] = (
                COMMENT_OR_LITERAL_RE.sub(
                    lambda match: " " + "\n" * match.group().count("\n"), content
                )
            )

    macros = set(LOG_MACROS)
    definitions = [
        (name, set(IDENTIFIER_RE.findall(body)))
        for content in contents.values()
        for name, body in DEFINE_RE.findall(content)
    ]
    # Follow nested wrappers, e.g. CC1120_DEASSERT_RETURN_IF_ERROR_CODE.
    while True:
        wrappers = {name for name, tokens in definitions if tokens & macros}
        if wrappers <= macros:
            break
        macros.update(wrappers)

    return sorted(
        path
        for path, content in contents.items()
        if set(IDENTIFIER_RE.findall(content)) & macros
    )


def render_header(count: int) -> str:
    return f"""#pragma once

// {GENERATED_NOTICE}

#include <stdint.h>

#ifdef __cplusplus
extern "C" {{
#endif

#define LOG_FILE_ID_COUNT {count}U

// Repo-relative paths of all files that use the logging macros,
// sorted alphabetically. A file's ID is its index in this table.
extern const char *const LOG_FILE_PATHS[LOG_FILE_ID_COUNT];

#ifdef __cplusplus
}}
#endif
"""


def _align_trailing_comments(lines: list[str]) -> list[str]:
    """Align // comments to match clang-format (AlignTrailingComments, SpacesBeforeTrailingComments: 2)."""
    prefixes: list[str] = []
    for line in lines:
        comment_idx = line.index("//")
        prefixes.append(line[:comment_idx].rstrip())

    max_prefix_len = max((len(prefix) for prefix in prefixes), default=0)
    aligned: list[str] = []
    for line in lines:
        comment_idx = line.index("//")
        prefix = line[:comment_idx].rstrip()
        comment = line[comment_idx:]
        pad = max_prefix_len - len(prefix) + 2
        aligned.append(f"{prefix}{' ' * pad}{comment}")
    return aligned


def render_source(paths: list[str]) -> str:
    raw_lines = [f'    "{p}",  // {i}' for i, p in enumerate(paths)]
    table = "\n".join(_align_trailing_comments(raw_lines))
    return f"""// {GENERATED_NOTICE}

#include "obc_log_file_ids.h"

const char *const LOG_FILE_PATHS[LOG_FILE_ID_COUNT] = {{
{table}
}};
"""


def render_json(paths: list[str]) -> str:
    return json.dumps({"format_version": 1, "files": paths}, indent=2) + "\n"


def render_cmake(paths: list[str]) -> str:
    # The list position is the same ID used by the C table and decoder JSON.
    lines = "\n".join(f"    {json.dumps(path)}" for path in paths)
    return f"# {GENERATED_NOTICE}\nset(LOG_FILE_ID_SOURCES\n{lines}\n)\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="verify generated files are up to date"
    )
    parser.add_argument(
        "--repo-root",
        type=Path,
        default=REPO_ROOT,
        help="source root to scan (defaults to this script's repository)",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        help="write build-local artifacts, including log_file_ids.cmake",
    )
    args = parser.parse_args()

    repo_root = args.repo_root.resolve()
    out_dir = args.output_dir or repo_root / "obc" / "shared" / "logging"
    paths = find_logging_files(repo_root)
    if len(paths) > 0xFFFF:
        parser.error("too many log files: 0xFFFF is reserved for unknown files")
    outputs = {
        out_dir / HEADER_PATH.name: render_header(len(paths)),
        out_dir / SOURCE_PATH.name: render_source(paths),
        out_dir / JSON_PATH.name: render_json(paths),
    }
    if args.output_dir:
        outputs[out_dir / "log_file_ids.cmake"] = render_cmake(paths)

    if args.check:
        stale = [
            p
            for p, content in outputs.items()
            if not p.exists() or p.read_text() != content
        ]
        if stale:
            for p in stale:
                print(f"STALE: {p}", file=sys.stderr)
            print("Run scripts/gen_log_file_ids.py to regenerate.", file=sys.stderr)
            return 1
        print("Log file ID tables are up to date.")
        return 0

    out_dir.mkdir(parents=True, exist_ok=True)
    changed = []
    for path, content in outputs.items():
        if path.exists() and path.read_text() == content:
            continue
        path.write_text(content)
        changed.append(path)
        print(f"Wrote {path}")
    print(f"{len(paths)} files in the log file ID table.")
    if out_dir / JSON_PATH.name in changed:
        print("Decode these firmware logs with this build's log_file_ids.json.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
